// Settings, automatic page-turn, the résumé picker and the autofill pop-up's data tabs — in real Chromium.
import { patchedExtension, launch } from './lib.mjs'
import { serve } from './mockjob.mjs'
const srv = serve(4100)
const { context, sw } = await launch(patchedExtension())
const log = (...a) => console.log(...a)
let fails = 0
const check = (label, ok, extra = '') => { log(ok ? 'PASS' : 'FAIL', label, extra); if (!ok) fails++ }
const login = await context.newPage()
await login.goto('http://localhost:3000/api/dev-signin'); await login.waitForTimeout(6000)
const SR = (p, fn, arg) => p.evaluate(({ fn, arg }) => new Function('r', 'a', fn)(document.querySelector('#saaf-overlay-host').shadowRoot, arg), { fn, arg })
const text = (p, sel) => SR(p, 'return (r.querySelector(a)?.innerText ?? "").replace(/\\s+/g," ").trim()', sel)
const click = (p, sel) => SR(p, 'r.querySelector(a).click()', sel)
const open = async (path) => { const p = await context.newPage(); await p.goto('http://localhost:4100' + path); await p.waitForSelector('#saaf-overlay-host', { state: 'attached', timeout: 20000 }); await p.waitForTimeout(4500); return p }
const store = (k) => sw.evaluate(async (k) => (await chrome.storage.local.get(k))[k] ?? null, k)

// ---- Settings (Jobright: "Autofill After Page Turn", "Default Plugin View")
let a = await open('/ez/job')
await click(a, '#gear'); await a.waitForTimeout(400)
check('the gear opens Settings in the panel', /Autofill After Page Turn/.test(await text(a, '#sv')) && /Default Plugin View/.test(await text(a, '#sv')))
check('defaults are Automatically + Expanded', await SR(a, 'return r.querySelector("input[name=pageTurn][value=auto]").checked && r.querySelector("input[name=view][value=expanded]").checked'))
await SR(a, 'r.querySelector("input[name=pageTurn][value=manual]").click(); r.querySelector("input[name=view][value=minimized]").click()'); await click(a, '#svsave'); await a.waitForTimeout(900)
const saved = await store('jxSettings')
check('Save stores both choices', saved?.pageTurn === 'manual' && saved?.view === 'minimized', JSON.stringify(saved))
const b = await context.newPage(); await b.goto('http://localhost:4100/ez/job'); await b.waitForSelector('#saaf-overlay-host', { state: 'attached', timeout: 20000 }); await b.waitForTimeout(3500)
check('"Minimized" starts collapsed to the edge tab', await SR(b, 'return r.getElementById("panel").hidden && !r.getElementById("tab").hidden'))

// ---- Automatic page turn on a two-step single-page application
await sw.evaluate(() => chrome.storage.local.set({ jxSettings: { pageTurn: 'auto', view: 'expanded' } }))
const c = await open('/steps')
await click(c, '#go'); await c.waitForTimeout(9000)
check('step 1 filled', !!(await c.evaluate(() => fn.value)) && !!(await c.evaluate(() => em.value)))
await c.evaluate(() => document.getElementById('next').click()); await c.waitForTimeout(10000)
const s2 = await c.evaluate(() => ({ ph: ph?.value, li: li?.value }))
check('AUTOMATICALLY: step 2 is filled with no click', !!s2.ph || !!s2.li, JSON.stringify(s2))
await sw.evaluate(() => chrome.storage.local.set({ jxSettings: { pageTurn: 'manual', view: 'expanded' } }))
const d = await open('/steps')
await click(d, '#go'); await d.waitForTimeout(9000)
await d.evaluate(() => document.getElementById('next').click()); await d.waitForTimeout(4500)
const s3 = await d.evaluate(() => ({ ph: ph?.value, li: li?.value }))
check('MANUALLY: step 2 is left alone and the panel says so', !s3.ph && !s3.li && /new step/.test(await text(d, '#gonote')), await text(d, '#gonote'))
await sw.evaluate(() => chrome.storage.local.set({ jxSettings: { pageTurn: 'auto', view: 'expanded' } }))

// ---- Résumé picker
const e = await open('/ez/job')
await click(e, '#rrow'); await e.waitForTimeout(3500)
const rows = await SR(e, 'return [...r.querySelectorAll(".afm-opt")].map(o=>o.textContent.trim().replace(/\\s+/g," "))')
log('picker rows:', JSON.stringify(rows))
check('picker lists the person\'s résumés, a PRIMARY badge, and "Apply without resume"', rows.length >= 2 && rows.some((x) => /PRIMARY/.test(x)) && rows.at(-1) === 'Apply without resume')
check('the preview shows the résumé text', (await text(e, '#rp-prev')).length > 200, (await text(e, '#rp-prev')).slice(0, 60))
check('Continue is disabled until the choice changes', await SR(e, 'return r.querySelector("#rp-go").disabled'))
await SR(e, 'r.querySelector(".afm-opt[data-id=none]").click()'); await e.waitForTimeout(300)
await click(e, '#rp-go'); await e.waitForTimeout(3000)
check('"Apply without resume" is remembered and nothing is attached', (await store('chosenResume'))?.none === true && /none yet/.test(await text(e, '#rname')), await text(e, '#rname'))
await click(e, '#rrow'); await e.waitForTimeout(3000)
await SR(e, '[...r.querySelectorAll(".afm-opt")].find(o=>/PRIMARY/.test(o.textContent)).click()'); await e.waitForTimeout(300)
await click(e, '#rp-go'); await e.waitForTimeout(4000)
check('choosing a résumé again attaches it', /docx/i.test(await text(e, '#rname')), await text(e, '#rname'))

// ---- the pop-up's data tabs (read from the real account)
const f = await open('/ez/job')
await click(f, '#info'); await f.waitForTimeout(500)
await SR(f, 'r.querySelector(".afm-nav button[data-k=education]").click()'); await f.waitForTimeout(2500)
const fields = (p) => SR(p, 'return [...r.querySelectorAll(".afm-pane input")].map(i=>i.value).join(" | ")')
check('Education tab shows the school, degree and major', /IIM Sambalpur/.test(await fields(f)) && /MBA, General Management/.test(await fields(f)) && /General Management/.test(await fields(f)), (await fields(f)).slice(0, 160))
await SR(f, 'r.querySelector(".afm-nav button[data-k=work]").click()'); await f.waitForTimeout(2500)
check('Work Experience tab lists the companies', /ICICI Bank/.test(await fields(f)), (await fields(f)).slice(0, 120))
await SR(f, 'r.querySelector(".afm-nav button[data-k=skill]").click()'); await f.waitForTimeout(2500)
check('Skill tab shows chips', (await SR(f, 'return r.querySelectorAll(".afm-chips span").length')) > 3)
await SR(f, 'r.querySelector(".afm-nav button[data-k=pref]").click()'); await f.waitForTimeout(500)
await SR(f, 'const i=r.querySelector("#pf-exp"); i.value="18"; i.dispatchEvent(new Event("input",{bubbles:true}))'); await f.waitForTimeout(200)
check('Preference: a salary enables Update', !(await SR(f, 'return r.querySelector(".afm-update").disabled')))
await click(f, '.afm-update'); await f.waitForTimeout(600)
check('…and is stored for autofill', (await store('profile'))?.expectedCtcLakhs === '18')

log(fails ? `\n${fails} FAILED` : '\nALL PASSED')
await context.close(); srv.close()
