import { patchedExtension, launch } from './lib.mjs'
const { context, sw } = await launch(patchedExtension())
const log = (...a) => console.log(...a)
const login = await context.newPage()
await login.goto('http://localhost:3000/api/dev-signin'); await login.waitForTimeout(6000)
const t = (page, sel) => page.evaluate((sel) => (document.querySelector('#saaf-overlay-host')?.shadowRoot?.querySelector(sel)?.innerText ?? '').replace(/\s+/g, ' ').trim(), sel)
const click = (page, sel) => page.evaluate((sel) => document.querySelector('#saaf-overlay-host').shadowRoot.querySelector(sel).click(), sel)
const veeva = await context.newPage()
await veeva.goto('https://careers.veeva.com/job/20ac0b20-911a-46b7-a4b6-1399fe293625/product-manager-director-crossix-manhattan-ny/', { waitUntil: 'domcontentloaded' }); await veeva.waitForTimeout(6000)
log('Veeva page, panel before the icon:', (await veeva.locator('#saaf-overlay-host').count()) ? 'YES' : 'no')
const tab = await sw.evaluate(async () => { const [x] = await chrome.tabs.query({ url: '*://careers.veeva.com/*' }); return x })
await sw.evaluate((x) => globalThis.__jxToggle(x), tab)
await veeva.waitForSelector('#saaf-overlay-host', { state: 'attached', timeout: 20000 }); await veeva.waitForTimeout(5000)
log('after the icon:', (await t(veeva, '#support')).slice(0, 80), '| Autofill enabled:', await veeva.evaluate(() => !document.querySelector('#saaf-overlay-host').shadowRoot.getElementById('go').disabled))
const popup = context.waitForEvent('page', { timeout: 30000 })
await click(veeva, '#go')
const lever = await popup
await lever.waitForLoadState('domcontentloaded'); await lever.waitForTimeout(16000)
log('opened by itself:', lever.url().split('?')[0])
log('panel there     :', (await t(lever, '#support')).slice(0, 60))
log('form values     :', JSON.stringify(await lever.evaluate(() => Object.fromEntries([...document.querySelectorAll('input[type=text],input[type=email],input[type=tel]')].filter((i) => i.value).map((i) => [i.name || i.id, i.value])))))
log('asks to submit  :', (await t(lever, '#submitbox')).slice(0, 60), '(NOT pressed)')
await lever.screenshot({ path: 'real-veeva-lever.png' })
await context.close()
