import { patchedExtension, launch } from './lib.mjs'
import { serve } from './mockjob.mjs'
const srv = serve(4100)
const dir = patchedExtension()
const { context, sw } = await launch(dir)
const log = (...a) => console.log(...a)
const page = await context.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
await page.goto('http://localhost:3000/api/dev-signin'); await page.waitForTimeout(6000)

const job = await context.newPage()
job.on('pageerror', (e) => errors.push('job: ' + String(e)))
await job.goto('http://localhost:4100/job')
await job.waitForSelector('#saaf-overlay-host', { state: 'attached', timeout: 15000 })
log('panel mounted: yes')
await job.waitForTimeout(6000) // connect + score
const text = async (sel) => (await job.locator(sel).first().innerText().catch(() => '')).replace(/\s+/g, ' ').trim()
log('account:', await text('#account'))
log('support:', await text('#support'))
log('match  :', (await text('#match')).slice(0, 220))
await job.screenshot({ path: 'panel-1.png' })

await job.locator('button#go').click()
await job.waitForTimeout(3500)
log('filled values:', JSON.stringify(await job.evaluate(() => ({ fn: fn.value, ln: ln.value, em: em.value, file: (() => { const f = document.querySelector('#rs').files[0]; return f ? f.name + ' (' + f.size + ' bytes)' : null })() }))))
log('dashboard:', (await text('#dash')).slice(0, 400))
log('report  :', (await text('#report')).slice(0, 300))
await job.screenshot({ path: 'panel-2.png' })
// ---- tailor (a real model call; leaves a saved résumé that cleanup.mjs removes)
await job.locator('button#tailor').click()
await job.waitForFunction(() => { const r = document.querySelector('#saaf-overlay-host').shadowRoot; const t = r.getElementById('tailored'); return t && t.innerText.trim().length > 0 }, null, { timeout: 120000 }).catch(() => {})
log('tailored :', (await text('#tailored')).slice(0, 400))
log('account  :', await text('#account'))
await job.locator('button#go').click()
await job.waitForTimeout(3000)
log('file now :', await job.evaluate(() => { const f = document.querySelector('#rs').files[0]; return f ? f.name + ' (' + f.size + ' bytes)' : null }))
await job.screenshot({ path: 'panel-3.png' })
log('errors:', JSON.stringify(errors))
await context.close(); srv.close()
