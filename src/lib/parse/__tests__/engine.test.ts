import { readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { looksLikeInternship, parseResumeFile } from '../engine'

const AS_OF = new Date('2026-10-14T00:00:00Z')
const fixture = (p: string) => join(process.cwd(), p)

describe('internship rule', () => {
  it('keeps interns, apprentices, fellows and articleship out of the headline; keeps salaried trainees in', () => {
    for (const t of ['HR Operations Intern Scaleup Mission', 'Summer Analyst Goldman', 'Research Fellow', 'Articleship Deloitte', 'Apprenticeship Tata']) expect(looksLikeInternship(t), t).toBe(true)
    for (const t of ['Graduate Engineer Trainee Tata Motors', 'Programmer Analyst Trainee Infosys', 'Product Manager Zeta', 'Internal Audit Manager']) expect(looksLikeInternship(t), t).toBe(false)
  })
})

describe('engine on the synthetic résumés (committed fixtures)', () => {
  // Hand-computed: Mar 2022 – Oct 2026 = 56 months, Jul 2019 – Feb 2022 = 32, no overlap → 88.
  it('reads the same career identically from a single-column and a two-column PDF', async () => {
    for (const f of ['single-column', 'two-column', 'table-layout']) {
      const r = await parseResumeFile(readFileSync(fixture(`bench/corpus/synthetic/${f}.pdf`)), 'pdf', { asOf: AS_OF })
      expect(r.derived.total_experience_months, f).toBe(88)
      expect(r.derived.current_role?.employer, f).toMatch(/razorpay/i)
    }
  })
  // No "Experience" heading in this one; Jun 2024 – Oct 2026 (29) joined to Aug 2023 – May 2024 (10) = 39.
  it('reads a résumé with no Experience heading', async () => {
    const r = await parseResumeFile(readFileSync(fixture('bench/corpus/synthetic/rohan.pdf')), 'pdf', { asOf: AS_OF })
    expect(r.derived.total_experience_months).toBe(39)
  })
})

describe('local OCR', () => {
  const scan = fixture('tests/fixtures/resumes/scanned/scan-two-column.pdf')
  // The fixture is generated by `npm run audit:fixtures`; skip rather than fail where it has not been built.
  it.skipIf(!existsSync(scan))('reads a scanned two-column page in column order (no merge across the gutter)', async () => {
    const r = await parseResumeFile(readFileSync(scan), 'pdf', { asOf: AS_OF })
    expect(r.meta.ocr_used).toBe(true)
    expect(r.meta.layout_columns).toBe(2)
    expect(r.derived.total_experience_months).toBe(88)
  }, 60_000)
})

describe('PDF dates', () => {
  it('reads the fixed-width PDF date format', async () => {
    const { parsePdfDate } = await import('../pdf')
    expect(parsePdfDate("D:20210315123456+05'30'")).toBe('2021-03-15')
    expect(parsePdfDate('D:2021')).toBe('2021-01-01')
    expect(parsePdfDate('garbage')).toBeNull()
    expect(parsePdfDate('D:20211301')).toBeNull() // month 13
  })
})

describe('garbled text', () => {
  it('counts replacement and icon-font glyphs, not ordinary text', async () => {
    const { garbledRatio } = await import('../engine')
    expect(garbledRatio('Senior Product Manager')).toBe(0)
    expect(garbledRatio('�� ab')).toBeCloseTo(0.4, 5)
    expect(garbledRatio(' xx')).toBeGreaterThan(0.3)
  })
})

describe('wrapped dates', () => {
  it('rejoins a date a narrow column cut in two, and only that', async () => {
    const { repairWrappedDates } = await import('../engine')
    expect(repairWrappedDates('Design Engineer | Mercedes-Benz | Mar\n2022-Present')).toBe('Design Engineer | Mercedes-Benz | Mar 2022-Present')
    expect(repairWrappedDates('Product Manager | Jan 2021 –\nPresent')).toBe('Product Manager | Jan 2021 – Present')
    // a sentence that merely ends in a month must not swallow the next bullet
    expect(repairWrappedDates('We shipped the launch in March\nLed the rollout')).toBe('We shipped the launch in March\nLed the rollout')
  })
})

describe('missing dash', () => {
  it('restores the separator between two dates, nowhere else', async () => {
    const { repairMissingDashes } = await import('../engine')
    expect(repairMissingDashes('Yoga Instructor Jan 2022 Present')).toBe('Yoga Instructor Jan 2022 – Present')
    expect(repairMissingDashes('Mar 2022 Jul 2019')).toBe('Mar 2022 – Jul 2019')
    expect(repairMissingDashes('Python 3 years experience since 2019')).toBe('Python 3 years experience since 2019')
  })
})
